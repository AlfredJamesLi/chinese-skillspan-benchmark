"""Render verified corpus records as an editable, font-embedded vector PDF.

Input JSON retains record IDs, verbatim text, excerpt offsets, and frozen labels.
No annotation or source text is generated by this renderer. ReportLab is required.
CNSS_CN_FONT/CNSS_EN_FONT/CNSS_EN_BOLD optionally locate TrueType fonts.
"""
from pathlib import Path
import json,os,re
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib.colors import HexColor,white
ROOT=Path(__file__).resolve().parent
DATA=json.loads((ROOT/'annotation_examples_corpus_20261003.json').read_text(encoding='utf-8'))
pdfmetrics.registerFont(TTFont('CN',os.getenv('CNSS_CN_FONT','C:/Windows/Fonts/simsun.ttc'),subfontIndex=0))
pdfmetrics.registerFont(TTFont('EN',os.getenv('CNSS_EN_FONT','C:/Windows/Fonts/arial.ttf')))
pdfmetrics.registerFont(TTFont('ENB',os.getenv('CNSS_EN_BOLD','C:/Windows/Fonts/arialbd.ttf')))
FILL={'L':'#E3DDF6','K':'#B9EEF0','S':'#FAED99','T':'#C6EBCB'}
EDGE={'L':'#64439A','K':'#167E87','S':'#987500','T':'#278846'}
W=510.;PAD=10.;TEXT=W-2*PAD;CNFS=13.3;ENFS=10.8;CNL=19.;LEAD=13.5
def width(t,f,s):return pdfmetrics.stringWidth(t,f,s)
def wrap(t):
 out=[];line=''
 for w in t.split():
  test=(line+' '+w).strip()
  if line and width(test,'EN',ENFS)>TEXT:out.append(line);line=w
  else:line=test
 if line:out.append(line)
 return out
def layout(ex):
 parts=[];last=0
 for s in ex['spans']:
  assert ex['text'][s['start']:s['end']]==s['text']
  parts.append((ex['text'][last:s['start']],None));parts.append((s['text'],s['type']));last=s['end']
 parts.append((ex['text'][last:],None));placed=[];x=0.;row=0
 tokens=[]
 for t,k in parts:
  tokens.extend([(t,k)] if k else [(v,None) for v in re.findall(r'[A-Za-z]+|[^A-Za-z]',t)])
 for i,(t,k) in enumerate(tokens):
  if not t:continue
  tw=width(t,'CN',CNFS);total=tw+(11 if k else 0);reserve=0
  if i+1<len(tokens) and tokens[i+1][0] in '，。；：、）':reserve=width(tokens[i+1][0],'CN',CNFS)
  if x and x+total+reserve>TEXT:row+=1;x=0.
  assert total<=TEXT
  placed.append((x,row,t,k,tw));x+=total
 return placed,row+1
EX=DATA['examples']
for ex in EX:
 ex['layout'],ex['cn_lines']=layout(ex);ex['en_lines']=wrap(ex['english_explanation']);ex['height']=24+ex['cn_lines']*CNL+7+len(ex['en_lines'])*LEAD+8
H=sum(e['height'] for e in EX)+6*(len(EX)-1)+29
c=canvas.Canvas(str(ROOT/'annotation_examples_corpus_20261003.pdf'),pagesize=(W,H),pageCompression=1)
c.setTitle('Verbatim Chinese corpus examples with frozen human-reference annotations');c.setAuthor('Chinese-SkillSpan authors')
def text(x,y,t,font='EN',fs=ENFS,color='#202C39'):
 c.setFillColor(HexColor(color));c.setFont(font,fs);c.drawString(x,y,t)
x=5
for code,label in [('L','Language'),('K','Knowledge'),('S','Occupational skill'),('T','Transversal competence')]:
 c.setFillColor(HexColor(FILL[code]));c.roundRect(x,H-17,13,14,2,fill=1,stroke=0);text(x+3,H-14,code,'ENB',10,EDGE[code]);text(x+18,H-14,label,'EN',10.4);x+=width(label,'EN',10.4)+33
assert x<W
top=H-29
for i,ex in enumerate(EX):
 bottom=top-ex['height'];c.setFillColor(white);c.setStrokeColor(HexColor('#CBD7E3'));c.setLineWidth(.75);c.roundRect(.5,bottom+.5,W-1,ex['height']-1,5,fill=1,stroke=1)
 title=chr(97+i)+') '+ex['title'];meta=ex['source_id']+' | '+('excerpt' if ex['extent']=='contiguous excerpt' else 'full sentence')
 text(PAD,top-16,title,'ENB',11.2);mw=width(meta,'EN',9);assert PAD+width(title,'ENB',11.2)+15<W-PAD-mw;text(W-PAD-mw,top-16,meta,'EN',9,'#536270')
 basey=top-36
 for dx,line,t,k,tw in ex['layout']:
  xx=PAD+dx;yy=basey-line*CNL
  if k:
   c.setFillColor(HexColor(FILL[k]));c.roundRect(xx-1,yy-2,tw+2,CNFS+3,1.5,fill=1,stroke=0);c.setStrokeColor(HexColor(EDGE[k]));c.setLineWidth(.65);c.line(xx,yy-2,xx+tw,yy-2)
  text(xx,yy,t,'CN',CNFS,'#111820')
  if k:text(xx+tw+2,yy+3,k,'ENB',7.8,EDGE[k])
 y=basey-(ex['cn_lines']-1)*CNL-21
 for line in ex['en_lines']:text(PAD,y,line);y-=LEAD
 assert y+LEAD>=bottom+8,(ex['source_id'],y,bottom)
 top=bottom-6
c.showPage();c.save();print('Vector source-sample figure:',W,H,'pt; five verified records; L/K/S/T')
